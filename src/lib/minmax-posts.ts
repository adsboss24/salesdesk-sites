function normalizeRemoteMinMaxPost(raw: Record<string, unknown>, idx = 0): MinMaxPost {
  const slug = String(raw.slug || '');
  const title = String(raw.title || 'บทความการตลาดดิจิทัลและการปั้นแบรนด์');
  const category = String(raw.category || 'Digital Marketing Strategy');
  const rawImg = String(raw.featuredImage || '');

  const featuredImage = rawImg.startsWith('http')
    ? rawImg
    : rawImg.startsWith('/api/seo/cover')
    ? `https://seo.salesdesk-ai.com${rawImg}`
    : `https://seo.salesdesk-ai.com/api/seo/cover?slug=${encodeURIComponent(
        slug
      )}&title=${encodeURIComponent(title)}&category=${encodeURIComponent(category)}&client=minmax-media`;

  return {
    id: String(raw.id || `remote-minmax-${idx}`),
    slug,
    title,
    metaDescription: String(raw.metaDescription || ''),
    content: String(raw.content || ''),
    featuredImage,
    imageAlt: String(raw.imageAlt || title),
    author: String(raw.author || 'ทีมกลยุทธ์ MinMax Media'),
    authorRole: String(raw.authorRole || 'Digital Marketing Specialist'),
    category,
    readTime: String(raw.readTime || '6 นาที'),
    published: true,
    publishedAt: String(raw.publishedAt || new Date().toISOString()),
    updatedAt: String(raw.updatedAt || raw.publishedAt || new Date().toISOString()),
  };
}

export function mergeWithRemoteMinMaxPosts(remoteRaw: Record<string, unknown>[]): MinMaxPost[] {
  const remotePosts = remoteRaw
    .map((item, idx) => normalizeRemoteMinMaxPost(item, idx))
    .filter((p) => p.slug);
  const remoteSlugs = new Set(remotePosts.map((p) => p.slug));
  const localRest = getAllMinMaxPosts().filter((p) => !remoteSlugs.has(p.slug));
  return [...remotePosts, ...localRest];
}

export async function fetchAllLiveMinMaxPosts(): Promise<MinMaxPost[]> {
  try {
    const res = await fetch('https://seo.salesdesk-ai.com/api/seo/posts?client=minmax-media', {
      cache: 'no-store',
    });
    if (res.ok) {
      const data = await res.json();
      if (data?.success && Array.isArray(data.posts) && data.posts.length > 0) {
        return mergeWithRemoteMinMaxPosts(data.posts);
      }
    }
  } catch {
    // Fallback to local posts
  }
  return getAllMinMaxPosts();
}

export async function fetchLiveMinMaxPostBySlug(slug: string): Promise<MinMaxPost | undefined> {
  const decoded = decodeURIComponent(slug);
  const localMatch = getMinMaxPostBySlug(decoded);
  if (localMatch) return localMatch;

  try {
    const res = await fetch(
      `https://seo.salesdesk-ai.com/api/seo/posts?slug=${encodeURIComponent(decoded)}`,
      { cache: 'no-store' }
    );
    if (res.ok) {
      const data = await res.json();
      if (data?.success && data.post) {
        return normalizeRemoteMinMaxPost(data.post, 0);
      }
    }
  } catch {
    // Fallback
  }
  return undefined;
}
